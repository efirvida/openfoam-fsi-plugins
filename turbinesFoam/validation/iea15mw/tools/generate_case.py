def _sampling_keys(
    velocity_sample_radius: float,
    n_velocity_samples: int,
) -> str:
    """Render the ALM velocity-sampling keys, omitting any at its default.

    Emitting nothing at the defaults keeps the committed case byte-identical
    (both keys absent = the C++ point-sampling branch); each key appears only
    when its own value is overridden, so neither is silently pinned.
    """
    lines = []
    if float(velocity_sample_radius) != DEFAULT_VELOCITY_SAMPLE_RADIUS:
        lines.append(
            f"        velocitySampleRadius {float(velocity_sample_radius):g};"
        )
    if int(n_velocity_samples) != DEFAULT_N_VELOCITY_SAMPLES:
        lines.append(f"        nVelocitySamples {int(n_velocity_samples)};")
    return "\n".join(lines) + ("\n" if lines else "")


def _end_effects_block(
    active: str,
    tip_effects: str,
    root_effects: str,
) -> str:
    """Render the rotor-level ``endEffects`` block.

    The two tip-loss models (Glauert end effects here, Dag & Sorensen in
    ``tipCorrection``) are alternatives; the campaign runs them separately.
    With ``active off`` -- the default -- the coefficients are inert, so the
    block keeps the committed ``tipEffects off; rootEffects off;`` stub and the
    default render stays byte-identical. With ``active on`` it renders the
    resolved coefficients, both defaulting to ``on`` (the campaign's Glauert
    arm: ``odd/tasks/iea15mw-validation-campaign.md`` Fase B1).
    """
    if active == "off":
        tip_effects = "off"
        root_effects = "off"
    return (
        "        endEffects\n"
        "        {\n"
        f"            active {active};\n"
        "            endEffectsModel Glauert;\n"
        "            GlauertCoeffs\n"
        "            {\n"
        f"                tipEffects {tip_effects};\n"
        f"                rootEffects {root_effects};\n"
        "            }\n"
        "        }\n"
    )


