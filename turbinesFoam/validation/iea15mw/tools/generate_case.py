def render_field_uniform(
    speed: float, field: str, flow_axis: str = DEFAULT_FLOW_AXIS
) -> str:
    """0.org field dictionaries (uniform inflow, symmetry far field)."""
    velocity = float(speed)
    fields = inflow_fields(speed)
    uin = foam_vector(tuple(velocity * c for c in inflow_direction(flow_axis)))
    far = "        type symmetryPlane;"
    if field == "U":
        dims = "[0 1 -1 0 0 0 0]"
        header = "volVectorField"
        internal = f"uniform {uin}"
        inlet = f"type fixedValue;\n        value uniform {uin};"
        outlet = (
            "type inletOutlet;\n"
            "        inletValue uniform (0 0 0);\n"
            f"        value uniform {uin};"
        )
        ground = "type noSlip;"
    elif field == "p":
        dims = "[0 2 -2 0 0 0 0]"
        header = "volScalarField"
        internal = "uniform 0"
        inlet = "type zeroGradient;"
        outlet = "type fixedValue;\n        value uniform 0;"
        ground = "type zeroGradient;"
    elif field == "k":
        dims = "[0 2 -2 0 0 0 0]"
        header = "volScalarField"
        value = fields["k"]
        internal = f"uniform {value:.8g}"
        inlet = f"type fixedValue;\n        value uniform {value:.8g};"
        outlet = (
            "type inletOutlet;\n"
            "        inletValue uniform 0;\n"
            f"        value uniform {value:.8g};"
        )
        ground = f"type kqRWallFunction;\n        value uniform {value:.8g};"
    elif field == "omega":
        dims = "[0 0 -1 0 0 0 0]"
        header = "volScalarField"
        value = fields["omega"]
        internal = f"uniform {value:.8g}"
        inlet = f"type fixedValue;\n        value uniform {value:.8g};"
        outlet = (
            "type inletOutlet;\n"
            "        inletValue uniform 0;\n"
            f"        value uniform {value:.8g};"
        )
        ground = f"type omegaWallFunction;\n        value uniform {value:.8g};"
    elif field == "nut":
        dims = "[0 2 -1 0 0 0 0]"
        header = "volScalarField"
        internal = "uniform 0"
        inlet = "type fixedValue;\n        value uniform 0;"
        outlet = (
            "type inletOutlet;\n"
            "        inletValue uniform 0;\n"
            "        value uniform 0;"
        )
        ground = "type nutkWallFunction;\n        value uniform 0;"
    else:
        raise ValueError(f"unknown field {field!r}")

    far_block = "    bottom\n    {\n" + ground + "\n    }\n" + "\n".join(
        f"    {name}\n    {{\n{far}\n    }}"
        for name in ("top", "sideMinus", "sidePlus")
    )
    return foam_header(field, header) + f"""dimensions      {dims};

internalField   {internal};

boundaryField
{{
    inlet
    {{
        {inlet}
    }}

    outlet
    {{
        {outlet}
    }}

{far_block}
}}
"""


def render_fv_options(
    speed: float = RATED_SPEED,
    rpm: float = RATED_RPM,
    pitch_deg: float = RATED_PITCH_DEG,
    case_dir: Path = DEFAULT_CASE_DIR,
    n_elements: int = N_ELEMENTS,
    cone_angle: float = PRECONE_DEG,
    flow_axis: str = DEFAULT_FLOW_AXIS,
    tower: bool = True,
    hub: bool = False,
) -> str:
    """The neutral-baseline ``axialFlowTurbineALSource``.

    Three blades 120 deg apart, 147 ALM elements over 49 geometry segments,
    the 50 per-station P1 polars, end effects off and no ``tipCorrection``
    block. No rotational augmentation and no dynamic stall. ``flow_axis``
    selects the rotor-axis/inflow orientation (x = OpenFAST, y = Aeroelast).
    """
    tsr = tip_speed_ratio(speed, rpm)
    origin = turbine_origin()
    axis_vec = rotor_axis(flow_axis)
    free_stream = tuple(float(speed) * c for c in inflow_direction(flow_axis))
    polars = _polars_include_dir(case_dir)
    profiles = " ".join(blade_element_profiles())
    blade_rows = "\n".join(
        "                    ("
        + " ".join(f"{value:.9g}" for value in row)
        + ")"
        for row in blade_element_rows(pitch_deg)
    )
    hub_rows = render_cell_list(hub_element_rows(), indent="                ")
    if hub:
        hub_block = f"""        hub
        {{
            nElements 4;
            elementProfiles (cylinder);
            elementData
            (
{hub_rows}
            );
        }}
"""
    else:
        hub_block = ""
    tower_rows = render_cell_list(tower_element_rows(), indent="                ")
    tower_cd = tower_drag_coefficient()
    if tower:
        tower_block = f"""
        tower
        {{
            // The OpenFAST reference has TwrAero=True, TwrCd={tower_cd:.3g}; the
            // tower is excluded from the rotor total drag (RotThrust is rotor-only).
            includeInTotalDrag false;
            nElements {TOWER_N_ELEMENTS};
            elementProfiles (tower);
            elementData
            (
{tower_rows}
            );
        }}
"""
        tower_profile = (
            f"            tower {{ data ((-180 0 {tower_cd:.8g} 0)"
            f" (180 0 {tower_cd:.8g} 0)); }}"
        )
    else:
        tower_block = ""
        tower_profile = ""
    profile_blocks = "\n".join(
        f"""            {name}
            {{
                GaussianCoeffs
                {{
                    chordFactor 0.25;
                    dragFactor 1.0;
                    meshFactor 1;
                }}
                #include "{polars}/{name}.dat"
            }}"""
        for name in blade_profile_names()
    )
    return foam_header("fvOptions") + f"""turbine
{{
    type axialFlowTurbineALSource;
    active on;

    axialFlowTurbineALSourceCoeffs
    {{
        fieldNames (U);
        selectionMode cellSet;
        cellSet turbine;
        origin {foam_vector(origin)};
        axis {foam_vector(axis_vec)};
        verticalDirection (0 0 1);
        freeStreamVelocity {foam_vector(free_stream)};
        tipSpeedRatio {tsr:.8g};
        rotorRadius {ROTOR_RADIUS:.8g};
        azimuthalOffset 0;
        coneAngle {float(cone_angle):.8g};

        dynamicStall
        {{
            active off;
            dynamicStallModel LeishmanBeddoes;
        }}

        rotationalAugmentation
        {{
            active off;
            model DuSelig;
            a 1;
            b 1;
            d 1;
        }}

        endEffects
        {{
            active off;
            endEffectsModel Glauert;
            GlauertCoeffs
            {{
                tipEffects off;
                rootEffects off;
            }}
        }}

        blades
        {{
            blade1
            {{
                writePerf true;
                writeElementPerf true;
                elementType actuatorLineElement;
                nElements {int(n_elements)};
                elementProfiles
                (
                    {profiles}
                );
                elementData
                (
{blade_rows}
                );
            }}
            blade2
            {{
                $blade1;
                writePerf false;
                writeElementPerf false;
                azimuthalOffset 120;
            }}
            blade3
            {{
                $blade1;
                writePerf false;
                writeElementPerf false;
                azimuthalOffset 240;
            }}
        }}

{hub_block}{tower_block}        profileData
        {{
{profile_blocks}
            cylinder {{ data ((-180 0 1.1 0) (180 0 1.1 0)); }}
{tower_profile}
        }}
    }}
}}
"""


def _polars_include_dir(case_dir: Path) -> str:
    """Path to ``data/polars`` relative to the rendered ``case/system`` dir."""
    return Path(os.path.relpath(POLARS_DIR, Path(case_dir) / "system")).as_posix()


def outputs(
    speed: float = RATED_SPEED,
    rpm: float = RATED_RPM,
    pitch_deg: float = RATED_PITCH_DEG,
    domain: object = None,
    case_dir: Path = DEFAULT_CASE_DIR,
    n_elements: int = N_ELEMENTS,
    cone_angle: float = PRECONE_DEG,
    end_revs: float = DEFAULT_END_REVOLUTIONS,
    start_from: str = "startTime",
    flow_axis: str = DEFAULT_FLOW_AXIS,
    tower: bool = True,
    hub: bool = False,
    ranks: int = NUMBER_OF_SUBDOMAINS,
    write_interval_deg: float = WRITE_INTERVAL_DEG,
) -> dict[Path, str]:
    domain = _as_domain(domain)
    case_dir = Path(case_dir)
    system = case_dir / "system"
    constant = case_dir / "constant"
    zero = case_dir / "0.org"
    rendered: dict[Path, str] = {
        system / "blockMeshDict": render_block_mesh(domain, flow_axis),
        system / "topoSetDict": render_toposet(flow_axis),
        system / "controlDict": render_control_dict(
            speed, rpm, domain, end_revs, start_from, write_interval_deg
        ),
        system / "decomposeParDict": render_decompose_par(ranks),
        system / "fvSchemes": render_fv_schemes(),
        system / "fvSolution": render_fv_solution(),
        system / "fvOptions": render_fv_options(
            speed,
            rpm,
            pitch_deg,
            case_dir,
            n_elements,
            cone_angle,
            flow_axis,
            tower,
            hub,
        ),
        constant / "transportProperties": render_transport_properties(),
        constant / "turbulenceProperties": render_turbulence_properties(),
    }
    for field in ("U", "p", "k", "omega", "nut"):
        rendered[zero / field] = render_field_uniform(speed, field, flow_axis)
    return rendered


def check_outputs(rendered: dict[Path, str], case_dir: Path) -> bool:
    clean = True
    for path, expected in rendered.items():
        if not path.exists():
            print(f"missing generated file: {_display(path, case_dir)}", file=sys.stderr)
            clean = False
            continue
        current = path.read_text(encoding="utf-8")
        if current != expected:
            print(f"stale generated file: {_display(path, case_dir)}", file=sys.stderr)
            diff = difflib.unified_diff(
                current.splitlines(),
                expected.splitlines(),
                fromfile="current",
                tofile="expected",
                n=2,
            )
            print("\n".join(list(diff)[:40]), file=sys.stderr)
            clean = False
    return clean


def _display(path: Path, case_dir: Path) -> str:
    try:
        return str(path.relative_to(case_dir))
    except ValueError:
        return str(path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--speed", type=float, default=RATED_SPEED)
    parser.add_argument("--rpm", type=float, default=RATED_RPM)
    parser.add_argument("--pitch", type=float, default=RATED_PITCH_DEG)
    parser.add_argument("--mesh", choices=MESH_CHOICES, default="coarse")
    parser.add_argument("--n-elements", type=int, default=N_ELEMENTS)
    parser.add_argument("--cone-angle", type=float, default=PRECONE_DEG)
    parser.add_argument("--end-revs", type=float, default=DEFAULT_END_REVOLUTIONS)
    parser.add_argument(
        "--start-from",
        choices=("startTime", "latestTime"),
        default="startTime",
        help="controlDict startFrom; use latestTime to resume a decomposed run",
    )
    parser.add_argument(
        "--flow-axis",
        choices=FLOW_AXIS_CHOICES,
        default=DEFAULT_FLOW_AXIS,
        help="flow/rotor axis: y = Aeroelast/FSI (fluid +Y, default), x = OpenFAST",
    )
    parser.add_argument(
        "--domain-upstream",
        type=float,
        default=DEFAULT_UPSTREAM_D,
        help="upstream extent [rotor diameters]",
    )
    parser.add_argument(
        "--domain-downstream",
        type=float,
        default=DEFAULT_DOWNSTREAM_D,
        help="downstream extent [rotor diameters]",
    )
    parser.add_argument(
        "--domain-lateral",
        type=float,
        default=DEFAULT_LATERAL_D,
        help="lateral half-extent [rotor diameters]",
    )
    parser.add_argument(
        "--domain-fine-max",
        type=float,
        default=DEFAULT_FINE_MAX_D,
        help="downstream end of the refined region [rotor diameters]",
    )
    parser.add_argument(
        "--domain-fine-lat",
        type=float,
        default=DEFAULT_FINE_LAT_D,
        help="lateral half-width of the refined region [rotor diameters]",
    )
    parser.add_argument(
        "--domain-top",
        type=float,
        default=DEFAULT_DOMAIN_TOP,
        help="domain top [m] above the rotor (the floor is at -hub height)",
    )
    parser.add_argument(
        "--tower",
        choices=("on", "off"),
        default="on",
        help="include the tower ALM (from the WindIO tower; default on, like OpenFAST)",
    )
    parser.add_argument(
        "--hub",
        choices=("on", "off"),
        default="off",
        help="include the hub drag body; default off (AeroDyn has no hub aero)",
    )
    parser.add_argument(
        "--ranks",
        type=int,
        default=NUMBER_OF_SUBDOMAINS,
        help="numberOfSubdomains in decomposeParDict (must match --ntasks)",
    )
    parser.add_argument(
        "--write-interval-deg",
        type=float,
        default=WRITE_INTERVAL_DEG,
        help="wake snapshot every N degrees of rotation (writeInterval = N/360 * T_rev)",
    )
    parser.add_argument("--case-dir", type=Path, default=DEFAULT_CASE_DIR)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail (exit 1) if generated files are missing or stale; never writes",
    )
    args = parser.parse_args(argv)

    try:
        domain = domain_spec(
            args.mesh,
            args.domain_upstream,
            args.domain_downstream,
            args.domain_lateral,
            args.domain_fine_max,
            args.domain_fine_lat,
            args.domain_top,
        )
        rendered = outputs(
            args.speed,
            args.rpm,
            args.pitch,
            domain,
            args.case_dir,
            args.n_elements,
            args.cone_angle,
            args.end_revs,
            args.start_from,
            args.flow_axis,
            args.tower == "on",
            args.hub == "on",
            args.ranks,
            args.write_interval_deg,
        )
    except (KeyError, ValueError) as exc:
        print(f"case generation error: {exc}", file=sys.stderr)
        return 2

    if args.check:
        return 0 if check_outputs(rendered, Path(args.case_dir)) else 1

    for path, content in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(_display(path, PACKAGE))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
