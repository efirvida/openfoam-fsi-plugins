RATED_SPEED = 10.659
RATED_RPM = 7.518
RATED_PITCH_DEG = 0.0

# --- Rotor geometry (P0 radius decision) -------------------------------------
ROTOR_RADIUS = blade_geometry.ROTOR_RADIUS_PUBLISHED
ROTOR_DIAMETER = 2.0 * ROTOR_RADIUS
HUB_HEIGHT = 150.0
N_BLADES = 3
#: 50 geometry stations -> 49 segments; 147 = 3 elements per segment.
N_ELEMENTS = 147
#: 4 deg precone, applied through the source's `coneAngle` key (option b).
PRECONE_DEG = 4.0

# --- Domain and mesh (Phase VI D-normalised box, D/32) -----------------------
#: Box 20D x 8D x 5D around the rotor, hub height 150 m.
