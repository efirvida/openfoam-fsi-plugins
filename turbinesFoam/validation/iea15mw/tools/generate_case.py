"""Render the IEA 15-240-RWT rated-point case from the committed P0/P1 data.

The case skeleton mirrors the NREL Phase VI uniform-inflow case
(``validation/phaseVI/tools/generate_case.py``) scaled to the 15 MW rotor:
an 18-block hexahedral far-field box, the same boundary layout, the same
URANS solver/schemes and an ``axialFlowTurbineALSource`` neutral baseline.

Sources of truth (never edited here):

- ``data/iea15mw_blade.csv`` (P0) — chord, twist, chord mount and the ALM
  mounting angle for all 50 stations.
- ``data/polars/polar_NN.dat`` (P1) — one ``profileData`` polar per station.

Operating point (rated, below the rated wind speed of the reference):
``V = 10.659 m/s``, ``Omega = 7.518 rpm``, collective pitch ``0``.  The tip
speed ratio is *computed* as ``Omega*R/V`` with the P0 projected radius
``R = 120.67532316 m`` — it is not a guessed constant.

Precone decision (option b): the ``elementData`` radius column is the
*physical* along-blade radius (``HubRad + BlSpn``, tip 120.9699 m) and the
rotor is rendered with ``coneAngle 4``.  ``axialFlowTurbineALSource``
supports the cone directly (``coneAngle`` is a documented
``lookupOrDefault`` key, ``axialFlowTurbineALSource.C:83``), so the extra key
is the only cost, and it preserves the real blade geometry while the
projected tip lands exactly on ``rotorRadius``:
``120.9699*cos(4 deg) = 120.6753 m``.

Blade shape (AeroDyn v15): ``elementData`` also carries the prebend
(``axialDistance = -BlCrvAC``), the sweep (``azimuth = asin(BlSwpAC/radius)``)
and the curve angle (``curveAngle = BlCrvAng``, 7th column, tilting the ALM
section frame).  See ``odd/tasks/iea15mw-blade-geometry-mapping.md``.

Every generated file carries a "Generated by tools/generate_case.py" banner;
``--check`` re-renders in memory and fails when a file on disk is missing or
stale, without writing anything.

Usage:
    generate_case.py [--speed 10.659] [--rpm 7.518] [--pitch 0]
                     [--mesh coarse] [--n-elements 147] [--cone-angle 4]
                     [--mesh-factor F] [--end-revs 3]
                     [--velocity-sample-radius R] [--n-velocity-samples N]
                     [--snappy-disk-radius R] [--snappy-disk-half-thickness T]
                     [--snappy-wake-radius R] [--snappy-wake-upstream U]
                     [--snappy-wake-downstream D] [--snappy-tower-upstream U]
                     [--snappy-tower-downstream D] [--snappy-tower-z-min Z]
                     [--snappy-tower-z-max Z] [--snappy-tower-lateral-factor F]
                     [--snappy-wake-level-offset N]
                     [--start-from startTime|latestTime]
                     [--flow-axis x|y] [--case-dir DIR] [--check]

Force-kernel width: the rendered ``GaussianCoeffs/meshFactor`` (default 1.0)
scales the ALM/ASM projection epsilon. Published guidance is
``epsilon_opt = 0.25*c``; ``meshFactor 1`` gives 1.89 m inside the disk against
1.05 m at mid-span, and too wide a kernel weakens the near-wake induction.

Inflow sampling: ``axialFlowTurbineALSource`` already reads
``velocitySampleRadius`` (in units of the projection epsilon) and
``nVelocitySamples`` from its coeffs and forwards them to every blade, but the
committed case rendered neither, so every run to date used the point-sampling
branch. The keys are rendered only when they differ from their defaults, so the
default render stays byte-identical. Zormpa et al. 2024 (Wind Energy) ask for
the sample outside the force Gaussian (``rs/rg = 1.1`` with
``rg = 3*epsilon``, i.e. ``rs = 3.3*epsilon``) -- the value this knob exists to
test.

Tip-loss models: ``endEffects`` (Glauert) and ``tipCorrection`` (Dag &
Sorensen) are ALTERNATIVES modelling the same physics, run separately by the
campaign. Both default to off, so no existing case changes.
"""

