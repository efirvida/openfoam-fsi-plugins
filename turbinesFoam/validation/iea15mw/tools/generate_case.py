"""Render the IEA 15-240-RWT rated-point case from the committed P0/P1 data.

The case skeleton mirrors the NREL Phase VI uniform-inflow case
(``validation/phaseVI/tools/generate_case.py``) scaled to the 15 MW rotor:
an 18-block hexahedral far-field box, the same boundary layout, the same
URANS solver/schemes and an ``axialFlowTurbineALSource`` neutral baseline.

Sources of truth (never edited here):

- ``data/iea15mw_blade.csv`` (P0) — chord, twist, chord mount and the ALM
  mounting angle for all 50 stations.
- ``data/polars/polar_NN.dat`` (P1) — one ``profileData`` polar per station.

Operating point (rated, below the rated wind speed of the reference):
``V = 10.659 m/s``, ``Omega = 7.518 rpm``, collective pitch ``0``.  The tip
speed ratio is *computed* as ``Omega*R/V`` with the P0 projected radius
``R = 120.67532316 m`` — it is not a guessed constant.

Precone decision (option b): the ``elementData`` radius column is the
*physical* along-blade radius (``HubRad + BlSpn``, tip 120.9699 m) and the
rotor is rendered with ``coneAngle 4``.  ``axialFlowTurbineALSource``
supports the cone directly (``coneAngle`` is a documented
``lookupOrDefault`` key, ``axialFlowTurbineALSource.C:83``), so the extra key
is the only cost, and it preserves the real blade geometry while the
projected tip lands exactly on ``rotorRadius``:
``120.9699*cos(4 deg) = 120.6753 m``.

Every generated file carries a "Generated by tools/generate_case.py" banner;
``--check`` re-renders in memory and fails when a file on disk is missing or
stale, without writing anything.

Usage:
    generate_case.py [--speed 10.659] [--rpm 7.518] [--pitch 0]
                     [--mesh coarse] [--n-elements 147] [--cone-angle 4]
                     [--end-revs 3] [--case-dir DIR] [--check]
"""

