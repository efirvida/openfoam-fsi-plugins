def foam_vector(values: list[float] | tuple[float, ...]) -> str:
    parts = []
    for value in values:
        number = float(value)
        if number == 0.0:  # normalise -0.0 so the rendered text is stable
            number = 0.0
        parts.append(f"{number:.9g}")
    return "(" + " ".join(parts) + ")"


