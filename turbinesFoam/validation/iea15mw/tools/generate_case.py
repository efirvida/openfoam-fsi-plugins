def omega_from_rpm(rpm: float) -> float:
    """Rotor angular velocity [rad/s] from a shaft speed in rpm."""
    return float(rpm) * 2.0 * math.pi / 60.0


def tip_speed_ratio(speed: float, rpm: float, radius: float = ROTOR_RADIUS) -> float:
    """Tip speed ratio ``Omega*R/V`` from the operating point.

    Never hard-coded: the readiness note's proposed 9.0786 corresponds to
    7.6575 rpm, not the rated 7.518 rpm, so it is not reproduced here.
    """
    return omega_from_rpm(rpm) * float(radius) / float(speed)


def revolution_period(rpm: float) -> float:
    """One rotor revolution [s]."""
    return 2.0 * math.pi / omega_from_rpm(rpm)


def axis_extents(axis: str) -> list[float]:
    """Default-domain horizontal block extents [m] of one axis (x/y)."""
    domain = domain_spec()
    if axis == "x":
        return flow_breaks(domain)
    if axis == "y":
        return lateral_breaks(domain)
    raise KeyError(f"{axis!r} is not a horizontal axis (x/y)")


def _geometric_layer(length: float, first_cell: float, last_cell: float) -> tuple[int, float]:
    """Number of cells and OpenFOAM grading for a geometric layer [m].

    Returns ``(n, grading)`` with ``grading = last_cell/first_cell`` and ``n``
    chosen so the actual first cell is closest to ``first_cell``.
    """
    ratio = float(last_cell) / float(first_cell)
    best_n, best_err = 1, float("inf")
    for n in range(2, 4000):
        q = ratio ** (1.0 / (n - 1))
        first = float(length) * (q - 1.0) / (q**n - 1.0)
        err = abs(first - float(first_cell))
        if err < best_err:
            best_err, best_n = err, n
        if first < float(first_cell) * 0.5:
            break
    return best_n, ratio


def _growing_layer(length: float, first_cell: float, growth: float) -> tuple[int, float]:
    """Number of cells and grading for a layer growing at ``growth`` from
    ``first_cell`` over ``length``."""
    g = float(growth)
    n = max(
        1,
        int(
            math.ceil(
                math.log(1.0 + float(length) * (g - 1.0) / float(first_cell))
                / math.log(g)
            )
        ),
    )
    return n, g ** (n - 1)


def vertical_mesh(
    domain_top: float = DEFAULT_DOMAIN_TOP,
    mesh: str = "coarse",
) -> tuple[list[float], list[int], list[float]]:
    """Hub-anchored vertical mesh: breaks, cells and grading.

    The rotor/hub is at z = 0 and the floor at z = -``HUB_HEIGHT``. Below the
    hub the cells go from ``Z_GROUND_CELL`` (at the ground, for the wall
    function) up to the mesh's hub-adjacent size (``D/32`` coarse, ``D/64``
    fine); above the hub they grow at ``Z_GROWTH`` to ``domain_top``.
    """
    top = float(domain_top)
    if top <= 0.0:
        raise ValueError(f"domain top {top} must be above the hub (z = 0)")
    hub_cell = ROTOR_DIAMETER / MESH_D_OVER.get(mesh, MESH_D_OVER["coarse"])
    breaks = [-HUB_HEIGHT, 0.0, top]
    n_low, grade_low = _geometric_layer(HUB_HEIGHT, Z_GROUND_CELL, hub_cell)
    n_up, grade_up = _growing_layer(top, hub_cell, Z_GROWTH)
    return breaks, [n_low, n_up], [grade_low, grade_up]


def _as_domain(domain: object = None) -> dict[str, float | str]:
    """Accept a domain spec, a mesh name, or ``None`` (the default domain)."""
    if domain is None:
        return domain_spec()
    if isinstance(domain, str):
        return domain_spec(mesh=domain)
    if isinstance(domain, dict):
        return domain
    raise TypeError(f"unsupported domain {domain!r}")


def cell_count(domain: object = None) -> int:
    """Total hexahedral cell count of the domain/mesh."""
    domain = _as_domain(domain)
    total = sum(flow_cells(domain)) * sum(lateral_cells(domain))
    _, z_cells, _ = vertical_mesh(domain["top"], str(domain["mesh"]))
    return total * sum(z_cells)


def hub_cell_size(domain: object = None) -> float:
    """Finest hub-adjacent vertical cell [m]; the time-step constraint length."""
    domain = _as_domain(domain)
    breaks, z_cells, z_grading = vertical_mesh(domain["top"], str(domain["mesh"]))
    hub_adjacent = []
    for index, cells in enumerate(z_cells):
        sizes = _cell_sizes(
            breaks[index + 1] - breaks[index], cells, z_grading[index]
        )
        hub_adjacent.append(sizes[-1] if index == 0 else sizes[0])
    return max(hub_adjacent)


def inflow_fields(speed: float) -> dict[str, float]:
    """k and omega for the configured inflow turbulence intensity."""
    intensity = TURBULENCE_INTENSITY
    length = MIXING_LENGTH_D * ROTOR_DIAMETER
    k = 1.5 * (intensity * float(speed)) ** 2
    c_mu = 0.09
    omega = math.sqrt(k) / (c_mu**0.25 * length)
    return {"k": k, "omega": omega}


def _cell_sizes(length: float, cells: int, grading: float) -> list[float]:
    """OpenFOAM ``simpleGrading`` cell sizes for one block direction."""
    if cells < 1:
        raise ValueError("cells must be positive")
    if cells == 1:
        return [length]
    q = float(grading) ** (1.0 / (cells - 1))
    first = length * (q - 1.0) / (q**cells - 1.0)
    return [first * q**i for i in range(cells)]


