#: Flow/rotor-axis orientation. ``x`` = the OpenFAST/AeroDyn convention (X
#: downwind); ``y`` = the Aeroelast/FSI convention (fluid in +Y, blade axis +Z,
#: profiles in XY), used so the fluid and structural meshes coincide for FSI.
FLOW_AXIS_CHOICES = ("x", "y")
#: Default orientation. ``y`` = the Aeroelast/FSI frame the IEA 15 MW case exists
#: for (fluid +Y, rotor axis about Y, blade axis +Z); ``x`` = OpenFAST.
DEFAULT_FLOW_AXIS = "y"


def inflow_direction(flow_axis: str = DEFAULT_FLOW_AXIS) -> tuple[float, float, float]:
    """Unit inflow direction: +x (OpenFAST) or +y (Aeroelast)."""
    if flow_axis == "x":
        return (1.0, 0.0, 0.0)
    if flow_axis == "y":
        return (0.0, 1.0, 0.0)
    raise ValueError(f"unknown flow axis {flow_axis!r}")


def rotor_axis(flow_axis: str = DEFAULT_FLOW_AXIS) -> tuple[float, float, float]:
    """Rotor axis (upwind, opposite the inflow)."""
    direction = inflow_direction(flow_axis)
    return tuple(-value for value in direction)


def _role_to_physical(
    flow_axis: str, x_role: float, y_role: float, z_role: float
) -> tuple[float, float, float]:
    """Map the mesh roles (x=flow, y=lateral, z=vertical) to physical XYZ.

    The y-flow case is the proper rotation ``R_z(+90 deg)`` — flow role -> +Y,
    lateral role -> -X, vertical unchanged — so the block handedness (and thus
    the blockMesh face normals) is preserved.
    """
    if flow_axis == "x":
        return (x_role, y_role, z_role)
    return (-y_role, x_role, z_role)


