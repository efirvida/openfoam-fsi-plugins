MESH_CHOICES = ("coarse",)
#: Block breaks in D units (x/y absolute D; z hub offset in D).
BREAKS_D = {
    "x": [-5.0, -0.5, 8.0, 15.0],
    "y": [-4.0, -1.5, 1.5, 4.0],
    "z": [-2.5, 0.0, 2.5],
}
#: D/32 development mesh; identical relative resolution to Phase VI coarse.
