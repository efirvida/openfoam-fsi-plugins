def render_block_mesh(
    domain: object = None,
    flow_axis: str = DEFAULT_FLOW_AXIS,
) -> str:
    """18-block hexahedral blockMeshDict with six far-field patches.

    The mesh roles are x=flow, y=lateral, z=vertical; ``flow_axis`` maps them
    to physical coordinates (see ``_role_to_physical``). The vertical mesh is
    hub-anchored: z = 0 at the rotor, the floor at -``HUB_HEIGHT``.
    """
    domain = _as_domain(domain)
    z_breaks, z_cells, z_grading = vertical_mesh(domain["top"], str(domain["mesh"]))
    breaks = {"x": flow_breaks(domain), "y": lateral_breaks(domain), "z": z_breaks}
    cells = {"x": flow_cells(domain), "y": lateral_cells(domain), "z": z_cells}
    grading = {
        "x": [float(value) for value in BASE_FLOW_GRADING],
        "y": [float(value) for value in BASE_LAT_GRADING],
        "z": z_grading,
    }
    nx, ny, nz = (len(breaks[axis]) for axis in ("x", "y", "z"))

    def vertex(ix: int, iy: int, iz: int) -> int:
        return (iz * ny + iy) * nx + ix

    vertices = []
    for z in breaks["z"]:
        for y in breaks["y"]:
            for x in breaks["x"]:
                px, py, pz = _role_to_physical(flow_axis, x, y, z)
                vertices.append(f"    ({px:.9g} {py:.9g} {pz:.9g})")

    blocks = []
    faces: dict[str, list[str]] = {name: [] for name in PATCH_NAMES}
    for iz in range(nz - 1):
        for iy in range(ny - 1):
            for ix in range(nx - 1):
                v000 = vertex(ix, iy, iz)
                v100 = vertex(ix + 1, iy, iz)
                v110 = vertex(ix + 1, iy + 1, iz)
                v010 = vertex(ix, iy + 1, iz)
                v001 = vertex(ix, iy, iz + 1)
                v101 = vertex(ix + 1, iy, iz + 1)
                v111 = vertex(ix + 1, iy + 1, iz + 1)
                v011 = vertex(ix, iy + 1, iz + 1)
                blocks.append(
                    "    hex "
                    f"({v000} {v100} {v110} {v010} {v001} {v101} {v111} {v011}) "
                    f"({cells['x'][ix]} {cells['y'][iy]} {cells['z'][iz]}) "
                    f"simpleGrading ({grading['x'][ix]:.9g} "
                    f"{grading['y'][iy]:.9g} {grading['z'][iz]:.9g})"
                )
                if ix == 0:
                    faces["inlet"].append(f"            ({v000} {v001} {v011} {v010})")
                if ix == nx - 2:
                    faces["outlet"].append(f"            ({v100} {v110} {v111} {v101})")
                if iz == 0:
                    faces["bottom"].append(f"            ({v000} {v010} {v110} {v100})")
                if iz == nz - 2:
                    faces["top"].append(f"            ({v001} {v101} {v111} {v011})")
                if iy == 0:
                    faces["sideMinus"].append(f"            ({v000} {v100} {v101} {v001})")
                if iy == ny - 2:
                    faces["sidePlus"].append(f"            ({v010} {v011} {v111} {v110})")

    patch_types = {
        "inlet": "patch",
        "outlet": "patch",
        "bottom": "wall",
        "top": "symmetryPlane",
        "sideMinus": "symmetryPlane",
        "sidePlus": "symmetryPlane",
    }

    def patch(name: str) -> str:
        return (
            f"    {name}\n"
            "    {\n"
            f"        type {patch_types[name]};\n"
            "        faces\n"
            "        (\n"
            + "\n".join(faces[name])
            + "\n        );\n"
            "    }"
        )

    return (
        foam_header("blockMeshDict")
        + "scale 1;\n\nvertices\n(\n"
        + "\n".join(vertices)
        + "\n);\n\nblocks\n(\n"
        + "\n".join(blocks)
        + "\n);\n\nedges ();\n\nboundary\n(\n"
        + "\n".join(patch(name) for name in PATCH_NAMES)
        + "\n);\n\nmergePatchPairs ();\n"
    )


def render_toposet(flow_axis: str = DEFAULT_FLOW_AXIS) -> str:
    """One cellSet box enclosing the rotor disk, hub and the 4 deg cone."""
    origin = turbine_origin()
    if flow_axis == "x":
        half = (0.5 * ROTOR_DIAMETER, 1.0 * ROTOR_DIAMETER, 1.0 * ROTOR_DIAMETER)
    else:
        half = (1.0 * ROTOR_DIAMETER, 0.5 * ROTOR_DIAMETER, 1.0 * ROTOR_DIAMETER)
    minimum = tuple(origin[i] - half[i] for i in range(3))
    maximum = tuple(origin[i] + half[i] for i in range(3))
    return foam_header("topoSetDict") + f"""actions
(
    {{
        name turbine;
        type cellSet;
        action new;
        source boxToCell;
        box {foam_vector(minimum)} {foam_vector(maximum)};
    }}
);
"""


def render_control_dict(
    speed: float = RATED_SPEED,
    rpm: float = RATED_RPM,
    domain: object = None,
    end_revs: float = DEFAULT_END_REVOLUTIONS,
    start_from: str = "startTime",
    write_interval_deg: float = WRITE_INTERVAL_DEG,
) -> str:
    domain = _as_domain(domain)
    t_rev = revolution_period(rpm)
    end_time = float(end_revs) * t_rev
    # Write every `write_interval_deg` of rotation, so the wake snapshots are a
    # smooth animation at the natural rotor speed. Binary format keeps each
    # snapshot ~4x smaller than ascii; purgeWrite 0 keeps the full history.
    write_interval = (float(write_interval_deg) / 360.0) * t_rev
    return foam_header("controlDict") + f"""application {APPLICATION};
startFrom {start_from};
startTime 0;
stopAt endTime;
endTime {end_time:.8g};
deltaT {delta_t(domain, rpm):.8g};
writeControl runTime;
writeInterval {write_interval:.8g};
purgeWrite 0;
writeFormat binary;
writePrecision 10;
writeCompression off;
timeFormat general;
timePrecision 8;
runTimeModifiable true;
adjustTimeStep off;

libs
(
    "libturbinesFoam.so"
);
"""


