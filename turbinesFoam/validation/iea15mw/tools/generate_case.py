def blade_element_rows(pitch_deg: float = RATED_PITCH_DEG) -> list[list[float]]:
    """AFTAL blade rows
    ``(axialDistance radius azimuth chord chordMount pitch curveAngle)``.

    Physical along-blade radius (``HubRad + BlSpn``) with ``coneAngle 4``; the
    P0 loader owns the mount, the ``pitch = -(twist + collective)`` sign, the
    prebend (``axialDistance = -BlCrvAC``), the sweep (``azimuth``) and the
    ``BlCrvAng`` section tilt (``curveAngle``). The 7th column is additive: a
    6-column table keeps the legacy zero curve angle.
    """
    return blade_geometry.element_rows(BLADE_CSV, collective_pitch_deg=pitch_deg)


def hub_element_rows() -> list[list[float]]:
    """AFTAL hub rows ``(axialDistance height diameter)`` (7.94 m cylinder)."""
    return [
        [0.0, blade_geometry.HUB_RADIUS, blade_geometry.HUB_DIAMETER],
        [0.0, -blade_geometry.HUB_RADIUS, blade_geometry.HUB_DIAMETER],
    ]


def tower_element_rows() -> list[list[float]]:
    """Tower ALM rows ``(axialDistance height diameter)`` from the WindIO tower.

    ``height`` is along the vertical from the rotor/hub at the origin, so the
    tower is below the hub (negative heights); ``axialDistance`` is the tower's
    downwind offset (``-overhang``, since the rotor axis points upwind). The
    overhang is read from the WindIO nacelle (``drivetrain.overhang``), so the
    tower position is derived from the same geometry source as the blade.
    """
    overhang = blade_geometry.read_tower_overhang()
    return [
        [-overhang, station["z"] - HUB_HEIGHT, station["diameter"]]
        for station in blade_geometry.read_tower_table()
    ]


def tower_drag_coefficient() -> float:
    """Tower drag coefficient from the WindIO tower (AeroDyn ``TwrCd``)."""
    stations = blade_geometry.read_tower_table()
    return stations[0]["cd"] if stations else 1.1


