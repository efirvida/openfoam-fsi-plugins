def foam_vector(values: list[float] | tuple[float, ...]) -> str:
    return "(" + " ".join(f"{float(value):.9g}" for value in values) + ")"


def render_cell_list(values: list[list[float]], indent: str = "            ") -> str:
    return "\n".join(
        indent + "(" + " ".join(f"{float(value):.9g}" for value in row) + ")"
        for row in values
    )


def turbine_origin() -> tuple[float, float, float]:
    """Rotor centre in mesh coordinates: the hub at x = y = 0, z = hub height."""
    return (0.0, 0.0, HUB_HEIGHT)


def blade_profile_names() -> list[str]:
    """One ``profileData`` name per blade station, keyed by the AeroDyn id.

    The AeroDyn ``BlAFID`` is 1..50; the P1 polar files are ``polar_00`` ..
    ``polar_49`` in station order.
    """
    return [f"polar_{station:02d}" for station in range(50)]


def blade_element_profiles() -> list[str]:
    """``elementProfiles`` in station order.

    ``actuatorLineSource`` maps element ``i`` to
    ``elementProfiles[i*size/nElements]`` (``actuatorLineSource.C:251``), so a
    50-entry list distributes the per-station polars across the 147 elements
    without a family-interpolation step.
    """
    return blade_profile_names()


def blade_element_rows(pitch_deg: float = RATED_PITCH_DEG) -> list[list[float]]:
    """AFTAL blade rows ``(axialDistance radius azimuth chord chordMount pitch)``.

    Physical along-blade radius (``HubRad + BlSpn``) with ``coneAngle 4``; the
    P0 loader owns the mount and the ``pitch = -(twist + collective)`` sign.
    """
    return blade_geometry.element_rows(BLADE_CSV, collective_pitch_deg=pitch_deg)


def hub_element_rows() -> list[list[float]]:
    """AFTAL hub rows ``(axialDistance height diameter)`` (7.94 m cylinder)."""
    return [
        [0.0, blade_geometry.HUB_RADIUS, blade_geometry.HUB_DIAMETER],
        [0.0, -blade_geometry.HUB_RADIUS, blade_geometry.HUB_DIAMETER],
    ]


