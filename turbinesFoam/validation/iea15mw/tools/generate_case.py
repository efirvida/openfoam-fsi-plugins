def foam_vector(values: list[float] | tuple[float, ...]) -> str:
    parts = []
    for value in values:
        number = float(value)
        if number == 0.0:  # normalise -0.0 so the rendered text is stable
            number = 0.0
        parts.append(f"{number:.9g}")
    return "(" + " ".join(parts) + ")"


def render_cell_list(values: list[list[float]], indent: str = "            ") -> str:
    return "\n".join(
        indent + "(" + " ".join(f"{float(value):.9g}" for value in row) + ")"
        for row in values
    )


def turbine_origin() -> tuple[float, float, float]:
    """Rotor centre: the hub at the origin; the floor is z = -``HUB_HEIGHT``."""
    return (0.0, 0.0, 0.0)


def blade_profile_names() -> list[str]:
    """One ``profileData`` name per blade station, keyed by the AeroDyn id.

    The AeroDyn ``BlAFID`` is 1..50; the P1 polar files are ``polar_00`` ..
    ``polar_49`` in station order.
    """
    return [f"polar_{station:02d}" for station in range(50)]


def blade_element_profiles() -> list[str]:
    """``elementProfiles`` in station order.

    ``actuatorLineSource`` maps element ``i`` to
    ``elementProfiles[i*size/nElements]`` (``actuatorLineSource.C:251``), so a
    50-entry list distributes the per-station polars across the 147 elements
    without a family-interpolation step.
    """
    return blade_profile_names()


def blade_element_rows(pitch_deg: float = RATED_PITCH_DEG) -> list[list[float]]:
    """AFTAL blade rows
    ``(axialDistance radius azimuth chord chordMount pitch curveAngle)``.

    Physical along-blade radius (``HubRad + BlSpn``) with ``coneAngle 4``; the
    P0 loader owns the mount, the ``pitch = -(twist + collective)`` sign, the
    prebend (``axialDistance = -BlCrvAC``), the sweep (``azimuth``) and the
    ``BlCrvAng`` section tilt (``curveAngle``). The 7th column is additive: a
    6-column table keeps the legacy zero curve angle.
    """
    return blade_geometry.element_rows(BLADE_CSV, collective_pitch_deg=pitch_deg)


def hub_element_rows() -> list[list[float]]:
    """AFTAL hub rows ``(axialDistance height diameter)`` (7.94 m cylinder)."""
    return [
        [0.0, blade_geometry.HUB_RADIUS, blade_geometry.HUB_DIAMETER],
        [0.0, -blade_geometry.HUB_RADIUS, blade_geometry.HUB_DIAMETER],
    ]


def tower_element_rows() -> list[list[float]]:
    """Tower ALM rows ``(axialDistance height diameter)`` from the WindIO tower.

    ``height`` is along the vertical from the rotor/hub at the origin, so the
    tower is below the hub (negative heights); ``axialDistance`` is the tower's
    downwind offset (``-TOWER_OVERHANG``, since the rotor axis points upwind).
    """
    return [
        [-TOWER_OVERHANG, station["z"] - HUB_HEIGHT, station["diameter"]]
        for station in blade_geometry.read_tower_table()
    ]


def tower_drag_coefficient() -> float:
    """Tower drag coefficient from the WindIO tower (AeroDyn ``TwrCd``)."""
    stations = blade_geometry.read_tower_table()
    return stations[0]["cd"] if stations else 1.1


